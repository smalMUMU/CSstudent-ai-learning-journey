# 训练最小版 —— 先跑通"训练"的整个流程（T10 简化版）

# 一句话：教计算机"猜"一个最能代表这堆数的数。

# ---------------------------------------------------------------
# 数据（就是你之前造出来的 ys，一行直接抄过来）：
#   ys = [2, 5, 8, 11, 14, 17, 20, 23]
#
# 模型：用【一个数】 w 来代表它们（只有一个参数，不用 b）
#
# 标准答案：平均数 = 12.5
#   ⚠️ 但程序【不知道】这个答案 —— 它要靠梯度下降自己"猜"出来。
# ---------------------------------------------------------------


# ============ 任务 1：写梯度（唯一要新写的） ============
#
#   L(w)  = Σ (y - w)^2                    ← 损失（猜得有多差）
#   dL/dw = Σ 2*(y - w)*(-1) = -2*Σ(y - w)  ← 损失对 w 的导数
#
#   先写这个函数：
#
#       def dL_dw(w):
#           s = 0                  # 累加器
#           for y in ys:
#               s += 2 * (y - w) * (-1)
#           return s
#
#   然后打印看看：print(dL_dw(0))
#   —— 只要打印出一个数，就说明这步通了。


# ============ 任务 2：加训练循环 ============
#
#   w = 0                     # 起点（随便猜一个数）
#   alpha = 0.01              # 学习率
#   重复 500 次：
#       g = dL_dw(w)          # 梯度 —— 告诉你"往哪走"
#       w = w - alpha * g     # 挪一步（【这行你已经懂了】）


# ============ 任务 3：打印最后的 w ============
#
#   print(w)
#   —— 如果它接近 12.5，说明你第一次"训练"出了一个模型 ✅


# ---------------------------------------------------------------
# 提醒（都是你踩过的坑）：
#   · 累加器：s = 0 开头，循环里用 s += ...（不是 s = ...）
#   · alpha 太大可能震荡/发散 → 先从 0.01 试
#   · 循环变量 i 和 被更新的变量 w 要分开
#
# 代码你自己写，我不代劳 :)

# ---------- 从这里开始写 ----------
ys = [2, 5, 8, 11, 14, 17, 20, 23]
def dl_dw(w):
    s = 0
    for y in ys:
        s += 2 * (y - w) * (-1)
    return s
alpha = 0.01
w = 0
for i in range(501):
    g = dl_dw(w)
    w = w - alpha * g
print (w)