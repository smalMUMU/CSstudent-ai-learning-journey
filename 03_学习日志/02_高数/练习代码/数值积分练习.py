# 数值积分练习 —— T7（积分 / 计算机怎么算积分）
#
# 背景：数学上 ∫(0→1) x^2 dx = 1/3 ≈ 0.333333...
#       但计算机【不会求原函数】——它只会加减乘除。
#       所以它只能把面积【切成很多小块，一块块加起来】逼近真实值。
#       这就是"数值积分"，也是所有科学计算/图形学/工程仿真的基本手段。
#
# ---------------------------------------------------------------
# 任务一：写一个"矩形法"近似 ∫(0→1) x^2 dx
#
#   把 [0,1] 切成 n 个小块：
#     每块宽度 h = 1 / n
#     每块面积 ≈ （该块【左端点】的函数值） × h
#     把 n 块面积全部加起来 = 近似值
#
#   用 n = 10、100、1000、10000 各跑一次，
#   每次记录：【近似值】 和 【与 1/3 的误差】
#
# ---------------------------------------------------------------
# 任务二（这才是重点）：找出误差的规律
#
#   先【猜】：n 变成 10 倍时，误差会变成原来的多少？
#        A. 误差 ∝ 1/n     （n×10 → 误差 ÷10）
#        B. 误差 ∝ 1/n^2   （n×10 → 误差 ÷100）
#   猜完再跑，用数据验证你的猜测。
#
#   提示：把每次的误差都打印出来，排成一列看，规律自己会浮出来。
#
# ---------------------------------------------------------------
# 任务三（彩蛋，做完前两个再看）：
#   把"左端点"改成【梯形法】（每块用上底+下底的平均高度），
#   再跑一遍 n = 10、100、1000、10000，看误差规律有没有变化。
#   —— 你会发现一种方法比另一种"高级"，而且原因很漂亮。
#
# 提示：结构和你写过的梯度下降/牛顿法一样：起点 -> 循环 -> 累加 -> 打印
# 代码你自己写，我不代劳 :)

# ---------- 你的代码写在下面 ----------
def f(x):
    y = x ** 2
    return y
n = 10000
h = 1 / n
total = 0
for i in range(n):
    total += ((f(i * h) + f((i + 1) * h)) / 2) * h
err = abs(1/3 - total)
print(n, total, err)
