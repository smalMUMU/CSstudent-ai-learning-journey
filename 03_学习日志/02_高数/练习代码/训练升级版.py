#   ⚠️ 现在只有 w、没有 b（截距），所以不可能完全拟合 y = 3x+2 ——
#      **能学到"接近 3"就算成功**，这一步的目标就这个。


# ---------------------------------------------------------------
# 提醒：
#   · 累加器：s = 0，循环里 s += ...
#   · 求和要用【下标 i】同时取 xs[i] 和 ys[i]
#   · 如果 w 变成天文数字（发散），把 alpha 调小（如 0.0001）
#
# 代码你自己写，我不代劳 :)

# ---------- 从这里开始写 ----------
xs = list(range(8))
ys = []
for x in xs:
    ys.append(3 * x + 2)

def dl_dw(w):
    s = 0
    for i in range(len(xs)):
        s += -2 * (ys[i] - w * xs[i]) * xs[i]
    return s

alpha = 0.0001
w = 0
for i in range(500):
    w = w - alpha * dl_dw(w)
print(w)