# 目标：用牛顿法求 x^2 - 2 = 0 的根（也就是 √2 ≈ 1.41421356237...）
#
# 牛顿法迭代式：
#     x_new = x - f(x) / f'(x)
#   这里 f(x) = x^2 - 2 ，f'(x) = 2x
#   所以： x_new = x - (x^2 - 2) / (2x)
#
# 要求：
#   1. 从 x = 1 出发
#   2. 迭代 5 次，每次打印 x
#   3. 观察：第几步就精确到小数点后十几位了？
#
# 彩蛋（写完再看）：
#   - 牛顿法用了"二阶"信息（曲线的弯），收敛极快（平方收敛）→ 大概 4 步就到位
#   - 对比你上次写的梯度下降：跑了 50 步才到
#   - 这也解释了"牛顿法这么快，为什么深度学习不用它"（后面可以聊）
#
# 提示：
#   - 结构和你的梯度下降几乎一样：起点 -> 循环 -> 更新 -> 打印
#   - 区别只在于"更新公式"换了
