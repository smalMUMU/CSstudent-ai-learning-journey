# 目标：训练一个模型，让它自己学出 w 和 b
#
#   数据：xs = [0,1,2,...,7]，ys = 3*x + 2
#   模型：y = w*x + b
#   训练完应该：w ≈ 3，b ≈ 2
#
# ---------------------------------------------------------------
# 你要回忆出来的 5 块（背景文档里都有）：
#
#   ① 造数据
#   ② w 的梯度函数  dl_dw(w, b)
#        ∂L/∂w = Σ -2 * (y - (w*x + b)) * x
#
#   ③ b 的梯度函数  dl_db(w, b)
#        ∂L/∂b = Σ -2 * (y - (w*x + b))      ← 注意：不乘 x
#
#   ④ 训练循环
#        w = w - alpha * dl_dw(w, b)
#        b = b - alpha * dl_db(w, b)
#
#   ⑤ 打印 w, b
#
# ---------------------------------------------------------------
# 提示：
#   · 累加器：s = 0 开头，循环里 s += ...
#   · 遍历数据用 i 同时取 xs[i] 和 ys[i]
#   · alpha 从 0.001 试，迭代 5000 次

# ---------- 从这里开始写 ----------
xs = list(range(8))
ys = []
for x in xs:
    y = 3 * x + 2
    ys.append(y)

w = 0
b = 0
alpha = 0.001

def dl_dw(w, b):
    s = 0
    for i in range(len(xs)):
        s += -2 * (ys[i] - (w * xs[i] + b)) * xs[i]
    return s

def dl_db(w, b):
    s = 0
    for i in range(len(ys)):
        s += -2 * (ys[i] - (w * xs[i] + b))
    return s

for i in range(50001):
    w = w - alpha * dl_dw(w, b)
    b = b - alpha * dl_db(w, b)

print(w, b)