# 目标：近似算 ∫(0→1) x^2 dx  （数学上 = 1/3 ≈ 0.33333...）
#
#   用【两种方法】各算一遍：
#
#   方法一 · 左矩形法
#       切成 n 块，每块宽 h = 1/n
#       每块面积 ≈ f(左端点) × h
#
#   方法二 · 梯形法
#       切成 n 块，每块面积 ≈ (上底 + 下底) / 2 × h
#       也就是用"这一块左右两个端点的高度取平均"
#
#   n 分别取 10、100、1000、10000
#   每次打印：【n, 近似值, 误差(= |1/3 - 近似值|)】
#
# ---------------------------------------------------------------
# 写完后自己检查两件事：
#   - 两种方法的误差，随 n 变大的变化规律一样吗？
#   - 你还记得哪个规律是 1/n、哪个是 1/n^2 吗？

# ---------- 从这里开始写 ----------
def f(x):
    y = x ** 2
    return y
n = 10000
h = 1 / n
s = 0
m = 0
for i in range(n):
    s += h * (f((i + 1) * h) + f(i * h)) / 2
    m += f(i * h) * h
erro1 = abs(1/3 - s)
erro2 = abs(1/3 - m)
print(n, h, erro1, erro2)