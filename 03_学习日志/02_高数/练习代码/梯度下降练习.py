# ---------- 你的代码写在下面 ----------
def f(x):
    y = (x - 2) ** 2
    return y
#上面的是原来的f(x)  = (x - 2) ** 2，下面的函数是f'(x) = 2 * (x - 2)为原函数的导函数
def g(x):
    n = 2 * (x - 2)
    return n
alpha = 1.1
x = 0
for i in range(0,51):
    x = x - alpha * g(x)
    print(x)