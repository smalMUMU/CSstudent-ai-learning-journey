#   你要亲手"训练"一个模型：给一堆数据点，让它自己找出最贴合的那条直线 y = w*x + b。
#
#   它用到的全是你学过的东西：
#     · 偏导数（T9）—— 算梯度
#     · 链式法则（T4）—— 推导梯度时用到
#     · 梯度下降（T5）—— 一步步往下走
#     · "找最小值"（T5）—— "训练" = 把损失压到最小
#
# ---------------------------------------------------------------
# 任务：
#
# 1. 造数据
#    自己编 8 个 x（比如 0,1,2,...,7）
#    y = 3*x + 2  再加上一点【噪声】（加随机数），这样才像真实数据
#    真实答案：w = 3、b = 2 —— 训练完应该逼近这两个数
#
# 2. 定义损失 L(w, b)
#    L = 所有点 (y_i - (w*x_i + b))^2 的和
#    意思：每个点偏离直线的距离平方，全部加起来
#
# 3. 写两个梯度（偏导数）
#    dL/dw = -2 * Σ (y_i - y_pred_i) * x_i
#    dL/db = -2 * Σ (y_i - y_pred_i)
#    其中 y_pred_i = w*x_i + b
#
# 4. 梯度下降迭代（比如 500 次）
#    w = w - alpha * dL/dw
#    b = b - alpha * dL/db
#    （alpha 是学习率，从 0.01 左右开始试）
#
# 5. 打印收敛后的 w 和 b
#    看它们是否逼近真值 3 和 2
#
# ---------------------------------------------------------------
# 提醒（都是你踩过的坑）：
#   · 累加器：求和先 `s = 0`，循环里用 `s += ...`（不是 `s = ...`）
#   · 循环变量和被更新的变量分开：`i` 数圈，`w`/`b` 是被更新的值
#   · 括号：分子/分母里有 + - 时必须括起来
#   · 每个点求和时，累加器要在循环里【每次归零】再累加
#
