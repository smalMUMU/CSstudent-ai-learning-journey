public class Varydemo01{
    public static void main(String[] args)
    {
        int a = 10;
        System.out.println(a);
        System.out.println(a);
        System.out.println(a);

        int b = 20;
        System.out.println(a + b);

        a = 50;
        System.out.println(a);

        System.out.println("------------------------");

        int d = 100, e = 200, f = 300;
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}